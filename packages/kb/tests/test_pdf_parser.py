"""Tests for the hand-rolled PDF layout parser (D2).

Runs against the three real fixture PDFs in packages/kb/golden/pdf/.
All tests are pure-CPU (no live API calls) and use the -m "not live" gate.

Fixture PDFs were generated by golden/pdf/generate_fixtures.py:
  - 01-安康保障计划条款.pdf  (3 pages: H1=18pt, H2=15pt, body=10.5pt, table on p2)
  - 02-理赔指南.pdf          (2 pages)
  - 03-产品说明.pdf          (2 pages)
Every page has a 9pt header "星辉人寿保险股份有限公司" and footer "第 N 页".
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from anvil_kb.ingest.chunker import chunk_markdown
from anvil_kb.ingest.pdf import parse_pdf

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
PDF_DIR = Path(__file__).parent.parent / "golden" / "pdf"
CORPUS_DIR = Path(__file__).parent.parent / "golden" / "corpus"

CLAUSE_PDF = PDF_DIR / "01-安康保障计划条款.pdf"
GUIDE_PDF = PDF_DIR / "02-理赔指南.pdf"
PRODUCT_PDF = PDF_DIR / "03-产品说明.pdf"

ALL_PDFS = [CLAUSE_PDF, GUIDE_PDF, PRODUCT_PDF]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _norm(text: str) -> str:
    """Collapse all whitespace (including NBSP, ideographic space) into nothing.

    Used for "is this string present?" checks that shouldn't fail on
    typographic spacing differences between the PDF and the golden corpus.
    """
    return re.sub(r"\s+", "", text)


def _load_pdf(path: Path) -> str:
    """Read a fixture PDF and return the parsed markdown."""
    return parse_pdf(path.read_bytes())


# ---------------------------------------------------------------------------
# Test 7 (bad input) — run first so failures are obvious
# ---------------------------------------------------------------------------

def test_bad_input_raises_value_error() -> None:
    """Random bytes that are not a valid PDF must raise ValueError."""
    with pytest.raises(ValueError, match="not a valid PDF"):
        parse_pdf(b"\x00\x01\x02\x03NOT_A_PDF_AT_ALL" * 50)


def test_empty_bytes_raises_value_error() -> None:
    """Empty bytes must also raise ValueError."""
    with pytest.raises(ValueError, match="not a valid PDF"):
        parse_pdf(b"")


# ---------------------------------------------------------------------------
# Test 1 — header/footer removal
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("pdf_path", ALL_PDFS, ids=["条款", "理赔指南", "产品说明"])
def test_company_header_removed(pdf_path: Path) -> None:
    """Repeated page-header occurrences of the company name must be stripped.

    The header "星辉人寿保险股份有限公司" appears on every page (9pt, top zone).
    After parsing, the company name should appear at most ONCE in the output
    (because 03-产品说明.md legitimately mentions it in the body text once).
    Documents 01 and 02 have no body-text mention, so count must be 0 for
    those; document 03 may have 1 due to legitimate body content.

    Crucially, the number of occurrences must be LESS than the number of pages
    (i.e. the cross-page dedup worked — the header was not emitted once per page).
    """
    md = _load_pdf(pdf_path)
    normalised = _norm(md)
    company = _norm("星辉人寿保险股份有限公司")
    count = normalised.count(company)

    import pdfplumber
    with pdfplumber.open(pdf_path) as pdf:
        num_pages = len(pdf.pages)

    assert count < num_pages, (
        f"{pdf_path.name}: company header appears {count} times "
        f"(must be < {num_pages} pages — dedup must have reduced repetitions).\n"
        f"First 300 chars of output:\n{md[:300]}"
    )


@pytest.mark.parametrize("pdf_path", ALL_PDFS, ids=["条款", "理赔指南", "产品说明"])
def test_page_numbers_removed(pdf_path: Path) -> None:
    """Page-number footers like 「第1页」/ 「第 2 页」 must NOT appear in output."""
    md = _load_pdf(pdf_path)
    normalised = _norm(md)
    # Match patterns: 第N页, 第 N 页, N/M, - N -, etc.
    for page_num in range(1, 10):
        assert f"第{page_num}页" not in normalised, (
            f"{pdf_path.name}: page-number '第{page_num}页' leaked into output."
        )


# ---------------------------------------------------------------------------
# Test 2 — heading recognition (≥80% of corpus ## headings identified)
# ---------------------------------------------------------------------------

def _corpus_h2_headings(md_text: str) -> list[str]:
    """Extract the titles of all ## headings from a corpus markdown file."""
    return re.findall(r"^## (.+)", md_text, re.MULTILINE)


def _output_heading_lines(md_text: str) -> set[str]:
    """Return the text content of all heading lines (any level) in output md."""
    titles: set[str] = set()
    for line in md_text.splitlines():
        m = re.match(r"^#{1,3} (.+)", line)
        if m:
            titles.add(_norm(m.group(1)))
    return titles


@pytest.mark.parametrize(
    "pdf_path,corpus_path",
    [
        (CLAUSE_PDF, CORPUS_DIR / "01-安康保障计划条款.md"),
        (GUIDE_PDF, CORPUS_DIR / "02-理赔指南.md"),
        (PRODUCT_PDF, CORPUS_DIR / "03-产品说明.md"),
    ],
    ids=["条款", "理赔指南", "产品说明"],
)
def test_heading_recognition_80pct(pdf_path: Path, corpus_path: Path) -> None:
    """≥80% of the golden corpus ## headings must appear as heading lines in output."""
    corpus_md = corpus_path.read_text(encoding="utf-8")
    golden_headings = _corpus_h2_headings(corpus_md)
    assert golden_headings, f"No ## headings found in {corpus_path.name}"

    parsed_md = _load_pdf(pdf_path)
    output_heading_titles = _output_heading_lines(parsed_md)

    matched = [h for h in golden_headings if _norm(h) in output_heading_titles]
    ratio = len(matched) / len(golden_headings)

    assert ratio >= 0.80, (
        f"{pdf_path.name}: only {len(matched)}/{len(golden_headings)} "
        f"({ratio:.0%}) headings recognised (need ≥80%).\n"
        f"Missing: {[h for h in golden_headings if _norm(h) not in output_heading_titles]}\n"
        f"Output heading lines found: {sorted(output_heading_titles)}"
    )


