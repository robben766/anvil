# ---------------------------------------------------------------------------
# Test 5 — no double-printing of table content
# ---------------------------------------------------------------------------

def test_no_double_table_content() -> None:
    """「保险金额的30%」must not appear more times than in the source corpus.

    The corpus (01-安康保障计划条款.md) contains:
      - 1 occurrence in body text (第8条 sentence)
      - 3 occurrences in table rows (第1次/第2次/第3次)
    Total: 4 occurrences.  If bbox dedup fails, the same table rows would also
    be emitted as raw text lines, doubling the count to 7.  We assert ≤ 4.
    """
    md = _load_pdf(CLAUSE_PDF)
    normalised = _norm(md)
    target = _norm("保险金额的30%")
    count = normalised.count(target)

    # Ground-truth count from corpus
    corpus_md = (CORPUS_DIR / "01-安康保障计划条款.md").read_text(encoding="utf-8")
    expected_count = _norm(corpus_md).count(target)

    assert count <= expected_count, (
        f"'保险金额的30%' appears {count} times in output (corpus has {expected_count}; "
        "excess indicates bbox-based table dedup failed)."
    )


