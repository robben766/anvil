def test_chunk_markdown_compat_clause() -> None:
    """chunk_markdown(parse_pdf(条款pdf)) must not raise and produce ≥5 chunks."""
    md = _load_pdf(CLAUSE_PDF)
    chunks = chunk_markdown(md)
    assert len(chunks) >= 5, (
        f"Expected ≥5 chunks for 条款篇, got {len(chunks)}."
    )


def test_table_chunk_atomic_in_clause() -> None:
    """chunk_markdown output must contain at least one chunk starting with '|'.

    Tables must be emitted as atomic chunks by the chunker.
    """
    md = _load_pdf(CLAUSE_PDF)
    chunks = chunk_markdown(md)
    table_chunks = [c for c in chunks if c.content.startswith("|")]
    assert len(table_chunks) >= 1, (
        "No atomic table chunk (starting with '|') found in chunk_markdown output.\n"
        f"All chunk starts: {[c.content[:30] for c in chunks]}"
    )
